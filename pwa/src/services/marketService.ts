export function simulateMarketTick(quotes: MarketQuote[]): MarketQuote[] {
  return quotes.map((q) => {
    if (q.id === 'etf_afra') return q;
    const deltaRatio = (Math.random() - 0.48) * 0.004; // slight realistic upward bias
    const nextPrice = Math.max(100, Math.round(q.priceToman * (1 + deltaRatio)));
    const nextChange = Number((q.change24hPct + deltaRatio * 100).toFixed(2));
    const nextSparkline = [...q.sparkline.slice(1), nextPrice];
    return {
      ...q,
      priceToman: nextPrice,
      change24hPct: nextChange,
      sparkline: nextSparkline,
    };
  });
}
